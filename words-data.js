/* 學校地址 → 練習題（由短到長）：縣市、鄉鎮市區、路名…，再組成前半段、後半段、完整地址
   例：臺中市北區學士路100號 → 臺中市／北區／學士路／100號／臺中市北區／學士路100號／臺中市北區學士路100號
   拆得不理想時，老師可以在設定頁直接改題目 */
window.splitAddr = function(addr, school){
  let a = String(addr || '').replace(/\s+/g, '').replace(/^\d{3,6}/, '');   /* 去掉空白和開頭的郵遞區號 */
  if (!a) return school ? [String(school).trim()] : [];
  const parts = a.match(/.+?(?:縣|市(?=.)|區|鄉|鎮|村|里|鄰|大道|路|街|段|巷|弄|號|樓)|.+$/g) || [a];
  /* 「一段」「二段」接在路名後面（中山路一段） */
  const P = [];
  parts.forEach(p => { if (/段$/.test(p) && P.length && /(路|街|大道)$/.test(P[P.length-1])) P[P.length-1] += p; else P.push(p); });
  /* 第一個是縣市，第二個是鄉鎮市區（如果有） */
  const head = P.slice(0, /[區鄉鎮市]$/.test(P[1] || '') ? 2 : 1).join(''), tail = P.slice(head === P[0] ? 1 : 2).join('');
  const out = [];
  const add = s => { s = String(s || '').trim(); if (s.length >= 2 && !out.includes(s)) out.push(s); };
  if (school) add(school);
  P.forEach(add);
  add(head); add(tail); add(a);
  return out.slice(0, 12);
};
